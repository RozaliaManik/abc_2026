import json
import requests
from bs4 import BeautifulSoup

# Адрес сайта с цитатами знаменитых людей
URL = "https://quotes.toscrape.com"
HEADERS = {"User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64)"}

print("Отправка запроса к сайту...")
response = requests.get(URL, headers=HEADERS, timeout=10)
response.raise_for_status()  # Проверяем, что сайт успешно ответил

# Передаем HTML-код страницы парсеру BeautifulSoup
soup = BeautifulSoup(response.text, "lxml")

# Собираем все цитаты в список словарей
quotes = [
    {
        # Находим текст цитаты (тег span с классом text)
        "text": q.select_one("span.text").get_text(strip=True),
        # Находим имя автора (тег small с классом author) — исправили опечатку лабы!
        "author": q.select_one("small.author").get_text(strip=True),
    }
    for q in soup.select("div.quote")
]

# Сохраняем собранные данные в файл quotes.json в кодировке UTF-8
with open("quotes.json", "w", encoding="utf-8") as f:
    json.dump(quotes, f, ensure_ascii=False, indent=2)

print(f"Успешно спарсено {len(quotes)} цитат! Данные сохранены в файл quotes.json")


