# Дан номер месяца (1 — январь, 2 — февраль, ...). Вывести название соответствующего
# времени года ("зима", "весна" и т.д.).


m = int(input("Введите номер месяца года: "))

if m in (12, 1, 2):
    print("Это время года - зима")
elif m in (3, 4, 5):
    print("Это время года - весна")
elif m in (6, 7, 8):
    print("Это время года - лето")
elif m in (9, 10, 11):
    print("Это время года - осень")
else:
    print("")