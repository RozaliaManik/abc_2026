# Определение в коде переменных


# 1. Целочисленного типа
a = 42

# 2. Вещественного типа
b = 3.14

# 3. Логического типа
c = True

# 4. Строкового типа
d = "Привет, Розалия"

# 5. Пустого типа
e = None

# Выводим их типы
print(f"a = {a} -> тип: {type(a)}")
print(f"b = {b} -> тип: {type(b)}")
print(f"c = {c} -> тип: {type(c)}")
print(f"d = {d} -> тип: {type(d)}")
print(f"e = {e} -> тип: {type(e)}")