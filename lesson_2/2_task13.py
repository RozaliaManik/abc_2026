# В восточном календаре принят 60-летний цикл, состоящий из 12-летних подциклов,
# обозначаемых названиями цвета: зеленый, красный, желтый, белый и черный.
# В каждом подцикле годы носят названия животных: крысы, коровы, тигра, зайца, дракона,
# змеи, лошади, овцы, обезьяны, курицы, собаки и свиньи. По номеру года вывести его название,
# если 1984 год был началом цикла — годом зеленой крысы.

# Запрашиваем у пользователя год
year = int(input("Введите год: "))

# Считаем смещение относительно базового 1984 года
# (1984 год — это 0-й год цикла: зеленая крыса)
offset = year - 1984

# Списки цветов и животных в правильном порядке
colors = ["зеленый", "красный", "желтый", "белый", "черный"]
animals = [
    "крысы", "коровы", "тигра", "зайца", "дракона", "змеи",
    "лошади", "овцы", "обезьяны", "курицы", "собаки", "свиньи"
]

# Определяем индекс цвета и животного с помощью остатка от деления (%)
# Так как цвета меняются каждые 2 года, мы сначала делим смещение на 2, а потом берем остаток от 5
color_index = (offset // 2) % 5
animal_index = offset % 12

# Выводим понятный результат
print(f"Год {year} — это год {colors[color_index]} {animals[animal_index]}")
